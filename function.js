///function without parameter
function greet() {
    console.log("hello Soni")
}

greet();

///function with parameter
function greetUser(name) {
    console.log("hello " + name)
}
greetUser("Soni");
greetUser("John");
greetUser("Alice");

///function with two parameters
function add(a, b){
    console.log(a + b);

}
add(5, 10);
add(20, 30);

///function with three parameters
function multiply(a, b, c) {
    console.log(a * b * c);
}